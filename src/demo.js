import { MAX_BODY_BYTES, readBody } from './email.js';
import { proxySignup } from './proxy.js';

const SIGNUP_PATH = '/AccountV2/ConfirmEmail';
const CSP = [
  "default-src 'none'",
  "script-src 'self'",
  "style-src 'self'",
  "connect-src 'self'",
  "img-src 'self' data:",
  "font-src 'self'",
  "base-uri 'none'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  "object-src 'none'",
].join('; ');

export function secureResponse(response) {
  const headers = new Headers(response.headers);
  headers.set('Cache-Control', 'no-store');
  headers.set('Content-Security-Policy', CSP);
  headers.set('X-Content-Type-Options', 'nosniff');
  headers.set('X-Frame-Options', 'DENY');
  headers.set('Referrer-Policy', 'no-referrer');
  headers.set('Permissions-Policy', 'camera=(), microphone=(), geolocation=()');
  headers.set('Cross-Origin-Resource-Policy', 'same-origin');
  headers.set('Strict-Transport-Security', 'max-age=31536000');
  return new Response(response.body, {
    status: response.status, statusText: response.statusText, headers,
  });
}

const error = (message, status) => Response.json({ error: message }, { status });

export async function demoTest(request, env) {
  const started = performance.now();
  if (request.method !== 'POST') {
    return Response.json({ error: 'Use POST for demo tests.' }, {
      status: 405, headers: { Allow: 'POST' },
    });
  }
  const url = new URL(request.url);
  const origin = request.headers.get('origin');
  if (origin !== null && origin !== url.origin) {
    return error('Cross-origin demo requests are not allowed.', 403);
  }
  const contentType = request.headers.get('content-type') ?? '';
  if (contentType.split(';', 1)[0].trim().toLowerCase() !== 'application/json') {
    return error('Use application/json with an email string.', 415);
  }

  let bytes;
  try {
    bytes = await readBody(request);
  } catch {
    return error('Could not read request body.', 400);
  }
  if (bytes === null) return error(`Demo body exceeds ${MAX_BODY_BYTES} bytes.`, 413);
  const body = new TextDecoder().decode(bytes);
  let input;
  try {
    input = JSON.parse(body);
  } catch {
    return error('Request body must be valid JSON.', 400);
  }
  if (!input || typeof input !== 'object' || Array.isArray(input) ||
      typeof input.email !== 'string' || input.email.length > 512 ||
      Object.keys(input).length !== 1) {
    return error('Provide an object containing only an email string of at most 512 characters.', 400);
  }

  // Hash and forward the received bytes; only proxy-owned Clef headers are replaced.
  const digest = await crypto.subtle.digest('SHA-256', bytes);
  const bodySha256 = Array.from(new Uint8Array(digest), byte => byte.toString(16).padStart(2, '0')).join('');
  const transformValue = request.headers.get('X-Demo-Clef-Integration');
  const headers = new Headers(request.headers);
  headers.delete('X-Clef-Demo');
  // Same-host cookies and service credentials reach the origin, never the API JSON.
  const signupRequest = new Request(request, {
    headers, body: bytes, redirect: 'manual',
  });
  let processed;
  try {
    processed = await proxySignup(signupRequest, env);
  } catch {
    return error('Signup processing unavailable.', 503);
  }
  const { response, recordId } = processed;
  if (!recordId) return error('Classification record unavailable. The request was not forwarded.', 503);

  let record;
  let probabilities;
  try {
    // This request can read only the record generated by its own proxy execution.
    record = await env.DB.prepare(`
      SELECT id, ray_id, created_at, completed_at, status, verdict,
        probabilities_json, confidence, inference_ms, model, policy_version, error_code
      FROM classifications WHERE id = ?
    `).bind(recordId).first();
    if (!record || record.status === 'pending' || !record.completed_at) {
      return error('Classification record is unavailable or incomplete.', 503);
    }
    probabilities = record.probabilities_json === null ? null : JSON.parse(record.probabilities_json);
  } catch {
    return error('Completed classification record unavailable.', 503);
  }

  let originBody;
  try {
    originBody = await response.json();
  } catch {
    return error('Diagnostic origin did not return a readable result.', 502);
  }
  const received = originBody?.request;
  const receivedClef = originBody?.clef;
  if (!response.ok || response.headers.get('x-test-origin') !== 'clef-signup-test-origin' ||
      typeof originBody?.accepted !== 'boolean' || !Number.isInteger(originBody?.accountsCreated) ||
      typeof received?.method !== 'string' || typeof received?.path !== 'string' ||
      typeof received?.query !== 'string' || typeof received?.contentType !== 'string' ||
      typeof received?.bodySha256 !== 'string' || !Number.isInteger(received?.bodyBytes) ||
      !receivedClef || typeof receivedClef !== 'object' || Array.isArray(receivedClef)) {
    return error('Diagnostic origin unavailable or returned an unexpected result.', 502);
  }

  const probabilitiesPreserved = probabilities === null
    ? receivedClef.probabilities === null
    : receivedClef.probabilities !== null && typeof receivedClef.probabilities === 'object' &&
      !Array.isArray(receivedClef.probabilities) &&
      Object.keys(probabilities).length === Object.keys(receivedClef.probabilities).length &&
      Object.entries(probabilities).every(([key, value]) => receivedClef.probabilities[key] === value);
  const predictionsPreserved = receivedClef.status === record.status &&
    receivedClef.verdict === record.verdict && probabilitiesPreserved &&
    receivedClef.confidence === record.confidence && receivedClef.requestId === record.id &&
    receivedClef.model === record.model && receivedClef.policyVersion === record.policy_version &&
    receivedClef.errorCode === record.error_code;

  return Response.json({
    email: input.email,
    requestId: record.id,
    rayId: record.ray_id,
    status: record.status,
    verdict: record.verdict,
    confidence: record.confidence,
    probabilities,
    inferenceMs: record.inference_ms,
    totalMs: Math.round(performance.now() - started),
    model: record.model,
    policyVersion: record.policy_version,
    errorCode: record.error_code,
    request: {
      method: signupRequest.method,
      path: url.pathname,
      query: url.search,
      contentType,
      body,
      bodyBytes: bytes.byteLength,
      bodySha256,
    },
    origin: {
      status: response.status,
      accepted: originBody.accepted,
      accountsCreated: originBody.accountsCreated,
      receivedClef,
      predictionsPreserved,
      response: originBody,
      bodyPreserved: received.bodyBytes === bytes.byteLength && received.bodySha256 === bodySha256,
      methodPreserved: received.method === signupRequest.method,
      pathPreserved: received.path === url.pathname && received.query === url.search,
      contentTypePreserved: received.contentType === contentType,
      location: response.headers.get('location'),
    },
    integration: {
      transformApplied: transformValue === 'worker-route',
      transformHeader: 'X-Demo-Clef-Integration',
      transformValue,
      routing: 'worker-route',
      originalPath: SIGNUP_PATH,
    },
    record: { createdAt: record.created_at, completedAt: record.completed_at },
  });
}
